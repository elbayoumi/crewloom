        (self.root / '.crewloom/active_coordinator.json').unlink()
        (self.root / '.crewloom/active_workflow.json').write_text(json.dumps(
            {'project_root': str(self.root), 'workflow': 'other-workflow',
             'plan_sha256': 'c' * 64}))

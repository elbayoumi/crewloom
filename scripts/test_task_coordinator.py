def _builder(body):
    return ('from pathlib import Path\nimport sys\n'
            'target = Path(sys.argv[1])\n'
            'marker = sys.argv[2] if len(sys.argv) > 2 else ""\n'
            'target.parent.mkdir(parents=True, exist_ok=True)\n'
            + body)



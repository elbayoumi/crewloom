    def git_in(self, path, *arguments):
        result = subprocess.run(['git', *arguments], cwd=str(path),
                                env=repo_map.git_environment(), capture_output=True, text=True,
                                check=False, timeout=30)
        if result.returncode:
            raise AssertionError('git ' + ' '.join(arguments) + ' failed in ' + str(path)
                                 + ': ' + result.stderr.strip())
        return result.stdout.strip()


    def test_a_symlinked_worktree_path_is_refused(self):
        outside = Path(tempfile.mkdtemp(prefix='crewloom-redirect-'))
        self.addCleanup(shutil.rmtree, str(outside), True)
        batch = self.root / '.crewloom/worktrees/feature-batch'
        batch.mkdir(parents=True)

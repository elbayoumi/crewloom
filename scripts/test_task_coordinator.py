def _stand_in_provider(requests):
    """A provider stand-in that answers only from the real request payload.

    It reads the prompt the managed executor actually sent, returns the declared output paths
    through the adapter's own `validate_artifacts`, and records the host it was asked for. No
    network, CLI or credential is involved: the point is the orchestration around generation, not
    a model. Every claim about what was generated stays checkable from the recorded requests.
    """
    def generate(host, prompt, outputs, timeout=180, model=None, max_output_tokens=None):
        # W09: inside a batch the adapter is now told its output ceiling; the stand-in records it.
        payload = json.loads(prompt.split('\n', 1)[1])
        requests.append({'host': host, 'model': model, 'ceiling': max_output_tokens, 'task': payload['task'],
                         'inputs': [item['path'] for item in payload['inputs']],
                         'outputs': list(payload['outputs'])})
        function = 'double' if 'left' in payload['task'] else 'triple'
        content = GENERATED[function]
        artifacts = {'artifacts': [{'path': path, 'content': content} for path in outputs]}
        return model_host.validate_artifacts(artifacts, outputs), {
            'host': host, 'model_reported': None, 'model_requested': model,
            'usage': {'input_tokens': len(prompt), 'output_tokens': len(content)},
            'execution_boundary': 'fixture stand-in provider; no network, CLI or credential'}
    return generate


class CoordinatorFixture(unittest.TestCase):
    """A disposable bound Git project with three task workflows and one integration workflow.

    The frozen repository is built once per class and copied per test, because the interesting
    cost here is Git process latency: every refusal case needs a real repository, and building one
    from scratch in each of two dozen cases buys nothing that a copy does not.
    """

    template = None

    @classmethod
    def setUpClass(cls):
        temporary = tempfile.TemporaryDirectory(prefix='crewloom-coordinator-template-')
        cls.addClassCleanup(temporary.cleanup)
        cls.template = Path(temporary.name).resolve() / 'project'
        cls.template.mkdir()
        cls._build(cls.template)

    @staticmethod
    def _git(root, *arguments):
        result = subprocess.run(['git', *arguments], cwd=str(root), env=repo_map.git_environment(),
                                capture_output=True, text=True, check=True, timeout=30)
        return result.stdout.strip()

    @classmethod
    def _build(cls, root):
        cls._git(root, 'init', '-q')
        cls._git(root, 'config', 'gc.auto', '0')
        cls._git(root, 'config', 'maintenance.auto', 'false')
        cls._git(root, 'config', 'user.name', 'Coordinator fixture')
        cls._git(root, 'config', 'user.email', 'fixture@example.invalid')
        # The catalog role a plan names is resolved from the installed library, not from this
        # project, so the fixture stays a bare bound repository instead of copying a role tree.
        config = pb.default_config('coordinator-fixture', 'observe')
        (root / pb.CONFIG_NAME).write_text(json.dumps(config))
        pb.bootstrap(root, project_id='coordinator-fixture')
        (root / 'input.txt').write_text('frozen fixture input\n')
        (root / 'criteria.md').write_text('- Every declared output exists and passes its check.\n')
        (root / 'builder.py').write_text(_builder(
            'target.write_text("artifact for %s marked %s at the frozen base\\n"\n'
            '                   % (target.name, marker))\n'))
        (root / 'left.txt').write_text('base content\n')
        (root / 'verify_combined.py').write_text(ACCEPTANCE)
        (root / 'workflows').mkdir()
        for name in ('left', 'right', 'combine', 'integration'):
            plan = {'schema_version': 1, 'id': name + '-workflow', 'criteria': 'criteria.md',
                    'steps': [{'id': 'build', 'role': ROLE,
                               'summary': 'Build one independently scoped artifact',
                               'argv': ['python3', 'builder.py', name + '.txt', name],
                               'inputs': ['input.txt', 'builder.py'],
                               'outputs': [name + '.txt']}]}
            if name == 'integration':
                plan['steps'][0] = {'id': 'accept', 'role': 'qa-test-automation-engineer',
                                    'summary': 'Accept the combined result of every task',
                                    'argv': ['python3', 'verify_combined.py'],
                                    'inputs': ['input.txt', 'verify_combined.py', 'left.txt',
                                               'right.txt', 'combine.txt'],
                                    'outputs': ['artifacts/acceptance.json']}
            (root / 'workflows' / (name + '.json')).write_text(json.dumps(plan))
        (root / 'coordinator.json').write_text(json.dumps(cls.plan_definition()))
        cls._git(root, 'add', '.')
        cls._git(root, 'commit', '-qm', 'Freeze the coordinator fixture')

    @staticmethod
    def plan_definition():
        return {'schema_version': 1, 'id': 'feature-batch',
                'project_id': 'coordinator-fixture', 'base': 'HEAD', 'workers': 2,
                'tasks': [{'id': 'left', 'workflow': 'workflows/left.json', 'depends_on': []},
                          {'id': 'right', 'workflow': 'workflows/right.json', 'depends_on': []},
                          {'id': 'combine', 'workflow': 'workflows/combine.json',
                           'depends_on': ['left', 'right']}],
                'integration': {'workflow': 'workflows/integration.json'}}

    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='crewloom-coordinator-')
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve() / 'project'
        shutil.copytree(self.template, self.root, symlinks=True)
        binding = pb.load_binding(self.root, allow_moved=True)
        binding['project_root'] = str(self.root)
        (self.root / pb.BINDING_RELATIVE).write_text(json.dumps(binding))
        self.plan = json.loads((self.root / 'coordinator.json').read_text())
        self.base = self.git('rev-parse', 'HEAD')

    def git(self, *arguments):
        return self._git(self.root, *arguments)

    def write_plan(self):
        (self.root / 'coordinator.json').write_text(json.dumps(self.plan))

    def snapshot(self):
        return {str(path.relative_to(self.root)): (
            hashlib.sha256(path.read_bytes()).hexdigest(), path.stat().st_mode, path.stat().st_mtime_ns)
            for path in self.root.rglob('*') if path.is_file() and not path.is_symlink()
            # Git's own background maintenance may add object-store files while a test runs; refs,
            # the index, HEAD and every working file stay compared, so a coordinator write still shows.
            and path.relative_to(self.root).parts[:2] != ('.git', 'objects')}

    def cli(self, action, project_id='coordinator-fixture', *extra):
        return subprocess.run([sys.executable, str(SOURCE / 'crewloom.py'), 'coordinator', action,
                               '--project', str(self.root), '--project-id', project_id,
                               '--manifest', 'coordinator.json', *extra], cwd=str(self.root),
                              env=repo_map.git_environment(), capture_output=True, text=True,
                              timeout=180)

    def call(self, action, **kwargs):
        return tc.__dict__[action](self.root, 'coordinator.json', 'coordinator-fixture', **kwargs)

    def worktree(self, ident):
        return self.root / '.crewloom/worktrees/feature-batch' / ident


class PreflightBoundaries(CoordinatorFixture):
    def test_a_valid_dag_validates_without_writing_anything(self):
        before = self.snapshot()
        result = self.cli('validate')
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        report = json.loads(result.stdout)
        self.assertEqual(report['status'], 'validated')
        self.assertEqual(report['order'], ['left', 'right', 'combine'])
        self.assertEqual(report['base_commit'], self.base)
        self.assertEqual(self.snapshot(), before, 'Read-only preflight wrote project state')

    def test_a_missing_local_binding_is_refused_without_guessing_identity(self):
        (self.root / '.crewloom/binding.json').unlink()
        result = self.cli('validate')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('not bound', result.stdout)

    def test_a_foreign_project_identity_is_refused(self):
        result = self.cli('validate', 'another-project')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('project identity', result.stdout.lower())

    def test_a_dirty_tracked_base_is_refused_and_preserved(self):
        (self.root / 'input.txt').write_text('local uncommitted edit\n')
        before = (self.root / 'input.txt').read_text()
        result = self.cli('validate')
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual((self.root / 'input.txt').read_text(), before)

    def test_staged_changes_are_refused_and_preserved(self):
        (self.root / 'input.txt').write_text('staged user change\n')
        self.git('add', 'input.txt')
        before = self.snapshot()
        self.assertNotEqual(self.cli('validate').returncode, 0)
        self.assertEqual(self.snapshot(), before)

    def test_unknown_option_like_and_missing_base_refs_are_refused(self):
        for base in ('--help', 'no-such-ref', 'HEAD^{tree}', 'a b', '..'):
            self.plan['base'] = base
            self.write_plan()
            self.git('add', 'coordinator.json')
            self.git('commit', '--allow-empty', '-qm', 'Freeze base ' + base)
            before = self.snapshot()
            self.assertNotEqual(self.cli('validate').returncode, 0, base)
            self.assertEqual(self.snapshot(), before, base)
        self.plan['base'] = 'HEAD'
        self.write_plan()

    def test_a_ref_that_does_not_name_the_checked_out_head_is_refused(self):
        self.git('checkout', '-q', '-b', 'other-base')
        self.git('checkout', '-q', '-')
        self.plan['base'] = 'other-base'
        self.write_plan()
        self.git('add', 'coordinator.json')
        self.git('commit', '-qm', 'Freeze a mismatched base')
        self.assertNotEqual(self.cli('validate').returncode, 0)

    def test_cycles_duplicates_and_unknown_keys_are_refused_without_writes(self):
        cases = [
            lambda: self.plan['tasks'][0].__setitem__('depends_on', ['combine']),
            lambda: self.plan['tasks'][1].__setitem__('id', 'left'),
            lambda: self.plan['tasks'][0].__setitem__('depends_on', ['left']),
            lambda: self.plan['tasks'][0].__setitem__('depends_on', ['missing']),
            lambda: self.plan['tasks'][0].__setitem__('surprise', True),
            lambda: self.plan.__setitem__('workers', 5),
            lambda: self.plan.__setitem__('workers', 0),
            lambda: self.plan.__setitem__('workers', True),
            lambda: self.plan.__setitem__('unexpected', 1),
            lambda: self.plan.__setitem__('language', 'fr'),
        ]
        for mutate in cases:
            with self.subTest(mutate=mutate):
                original = json.loads(json.dumps(self.plan))
                mutate()
                self.write_plan()
                self.git('add', 'coordinator.json')
                self.git('commit', '--allow-empty', '-qm', 'Freeze an invalid manifest')
                before = self.snapshot()
                result = self.cli('validate')
                self.assertNotEqual(result.returncode, 0)
                self.assertIn('error', result.stdout.lower())
                self.assertEqual(self.snapshot(), before)
                self.plan = original
                self.write_plan()
                self.git('add', 'coordinator.json')
                self.git('commit', '--allow-empty', '-qm', 'Restore the valid manifest')

    def test_a_non_git_root_is_refused_and_an_outside_manifest_is_refused(self):
        plain = Path(tempfile.mkdtemp(prefix='crewloom-plain-'))
        self.addCleanup(shutil.rmtree, str(plain), True)
        (plain / 'coordinator.json').write_text('{}')
        with self.assertRaisesRegex(ValueError, 'git project|Git'):
            tc.validate(plain, 'coordinator.json', 'coordinator-fixture')
        outside = Path(tempfile.mkdtemp(prefix='crewloom-outside-'))
        self.addCleanup(shutil.rmtree, str(outside), True)
        (outside / 'other.json').write_text(json.dumps(self.plan))
        with self.assertRaisesRegex(ValueError, 'escapes'):
            tc.validate(self.root, '../' + str(outside)[1:].replace('/', '/'), 'coordinator-fixture')

    def test_a_task_workflow_without_an_integration_input_is_refused(self):
        plan = json.loads((self.root / 'workflows/integration.json').read_text())
        plan['steps'][0]['inputs'] = ['input.txt', 'builder.py']
        (self.root / 'workflows/integration.json').write_text(json.dumps(plan))
        self.git('add', 'workflows/integration.json')
        self.git('commit', '-qm', 'Narrow the integration inputs')
        before = self.snapshot()
        result = self.cli('validate')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('integration workflow must declare', result.stdout)
        self.assertEqual(self.snapshot(), before)

    def test_a_manual_task_step_is_refused_before_anything_runs(self):
        plan = json.loads((self.root / 'workflows/left.json').read_text())
        plan['steps'][0]['kind'] = 'task'
        (self.root / 'workflows/left.json').write_text(json.dumps(plan))
